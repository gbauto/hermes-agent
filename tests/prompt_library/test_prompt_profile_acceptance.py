    envelope["resolvedFrom"] = ["tac-builder-profile", "shared-safety"]

    monkeypatch.setattr(render_mod, "cn_version", lambda: "0.2.6")
    monkeypatch.setattr(render_mod, "cn_render", lambda *a, **kw: envelope)
    monkeypatch.setattr(render_mod, "cn_show", lambda name, project_dir: {"frontmatter": {"tags": ["tenant:other"]}})
    monkeypatch.setattr(render_mod, "check_profile_exists", lambda profile: True)

    result = render_profile("tac-builder", library_root=library_root)

    assert result["resolved_from"] == ["tac-builder-profile", "shared-safety"]


