def test_apply_patches_config_addendum_and_preserves_unrelated_keys(tmp_path, monkeypatch, mocked_canopy):
    from hermes_agent.prompt_library.apply import apply_render

    hermes_home = tmp_path / "home"
    profile_home = hermes_home / "profiles" / "tac-builder"
    profile_home.mkdir(parents=True)
    (profile_home / "SOUL.md").write_text("old soul\n", encoding="utf-8")
    (profile_home / "config.yaml").write_text(
        "model:\n  provider: openrouter\n  default: old-model\ntools:\n  enabled: true\nsystem_prompt_addendum: old addendum\n",
        encoding="utf-8",
    )
    library_root = hermes_home / "prompt-library"
    monkeypatch.setenv("HERMES_HOME", str(hermes_home))
    _write_manifest(library_root, hermes_home)

    result = apply_render("tac-builder", library_root=library_root, acknowledged_fossilization=True)

    updated = yaml.safe_load((profile_home / "config.yaml").read_text(encoding="utf-8"))
    assert updated["model"] == {"provider": "openrouter", "default": "old-model"}
    assert updated["tools"] == {"enabled": True}
    assert "Use board gbautomation" in updated["system_prompt_addendum"]
    assert Path(result["backup_dir"]).is_dir()
    assert Path(result["receipt_path"]).is_file()


def test_render_does_not_read_secret_files(tmp_path, monkeypatch, mocked_canopy):
    from hermes_agent.prompt_library.render import render_profile

    hermes_home = tmp_path / "home"
    hermes_home.mkdir()
    (hermes_home / ".env").write_text("HERMES_SHOULD_NOT_READ=1\n", encoding="utf-8")
    (hermes_home / "auth.json").write_text(json.dumps({"secret": "do-not-read"}), encoding="utf-8")
    library_root = hermes_home / "prompt-library"
    monkeypatch.setenv("HERMES_HOME", str(hermes_home))
    _write_manifest(library_root, hermes_home)

    original_open = builtins.open
    opened_secret_files: list[str] = []

    def recording_open(file, *args, **kwargs):
        path = str(file)
        if path.endswith("/.env") or path.endswith("/auth.json"):
            opened_secret_files.append(path)
        return original_open(file, *args, **kwargs)

    monkeypatch.setattr(builtins, "open", recording_open)
    render_profile("tac-builder", library_root=library_root)

    assert opened_secret_files == []


def test_prompts_cli_render_is_dry_run_by_default_with_fake_canopy(tmp_path):
    hermes_home = tmp_path / "home"
    library_root = hermes_home / "prompt-library"
    fake_bin = tmp_path / "bin"
    (library_root / "profiles").mkdir(parents=True)
    (library_root / ".canopy").mkdir()
    fake_bin.mkdir()

    manifest = {
        "schema": "hermes.prompt_profile.v1",
        "profile": "gelby-default",
        "tenant": "gbautomation",
        "owner": "greg",
        "render": {"adapter": "canopy", "prompt": "gelby-default", "params": {"name": "Gelby"}},
        "targets": {"soul": {"path": str(tmp_path / "live" / "SOUL.md"), "mode": "replace"}},
        "section_routes": [{"section": "identity", "target": "soul"}],
    }
    (library_root / "profiles" / "gelby-default.yaml").write_text(yaml.safe_dump(manifest), encoding="utf-8")
    fake_cn = fake_bin / "cn"
    fake_cn.write_text(
        "#!/usr/bin/env python3\n"
        "import json, sys\n"
        "if '--version' in sys.argv:\n"
        "    print('canopy/0.2.6')\n"
        "elif sys.argv[1] == 'render':\n"
        "    print(json.dumps({'success': True, 'name': sys.argv[2], 'version': 1, 'resolvedFrom': [sys.argv[2]], 'sections': [{'name': 'identity', 'body': 'Hello {{ name }}'}]}))\n"
        "elif sys.argv[1] == 'show':\n"
        "    print(json.dumps({'tags': ['tenant:gbautomation']}))\n",
        encoding="utf-8",
    )
    fake_cn.chmod(0o755)

    env = os.environ.copy()
    env["HERMES_HOME"] = str(hermes_home)
    env["PATH"] = f"{fake_bin}{os.pathsep}{env.get('PATH', '')}"
    completed = subprocess.run(
        [
            sys.executable,
            "-m",
            "hermes_cli.main",
            "prompts",
            "render",
            "gelby-default",
            "--library-root",
            str(library_root),
            "--json",
        ],
        cwd=Path(__file__).parents[2],
        env=env,
        text=True,
        capture_output=True,
        timeout=30,
        check=True,
    )
    result = json.loads(completed.stdout)

    assert result["dry_run"] is True
    assert Path(result["receipt_path"]).is_file()
    assert (library_root / "staging" / "gelby-default" / "SOUL.md.rendered").is_file()
    assert not (tmp_path / "live" / "SOUL.md").exists()


