def test_render_dry_run_writes_staging_and_receipt_only(tmp_path, monkeypatch, mocked_canopy):
    from hermes_agent.prompt_library.render import render_profile

    hermes_home = tmp_path / "home"
    library_root = hermes_home / "prompt-library"
    monkeypatch.setenv("HERMES_HOME", str(hermes_home))
    _write_manifest(library_root, hermes_home)

    result = render_profile("tac-builder", library_root=library_root)

    assert result["dry_run"] is True
    assert Path(result["receipt_path"]).is_file()
    assert (library_root / "staging" / "tac-builder" / "SOUL.md.rendered").read_text(encoding="utf-8").startswith("<!-- GENERATED BY hermes.prompt_profile.v1")
    assert (library_root / "staging" / "tac-builder" / "config_addendum.txt").read_text(encoding="utf-8").startswith("<!-- GENERATED BY hermes.prompt_profile.v1")
    assert not (hermes_home / "profiles" / "tac-builder" / "SOUL.md").exists()
    assert not (hermes_home / "profiles" / "tac-builder" / "config.yaml").exists()


